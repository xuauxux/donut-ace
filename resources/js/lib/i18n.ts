export const DICTIONARIES: Record<Locale, Dictionary> = { en, es, pt, de, fr, tr };

export function isLocale(value: unknown): value is Locale {
    return typeof value === 'string' && LOCALES.some((l) => l.id === value);
}

function fill(template: string, vars?: Record<string, string | number>): string {
    if (!vars) return template;

    return Object.entries(vars).reduce(
        (out, [key, value]) => out.split(`{${key}}`).join(String(value)),
        template,
    );
}

/** Translate a key, falling back to English and finally to the key itself. */
export function translate(
    locale: Locale,
    key: string,
    vars?: Record<string, string | number>,
): string {
    const dict = DICTIONARIES[locale] ?? en;
    const template =
        (dict as Record<string, string | undefined>)[key] ??
        (en as Record<string, string | undefined>)[key] ??
        key;

    return fill(template, vars);
}

/** True when English defines the key — used for optional strings (game names). */
export function hasTranslation(key: string): boolean {
    return Object.prototype.hasOwnProperty.call(en, key);
}
